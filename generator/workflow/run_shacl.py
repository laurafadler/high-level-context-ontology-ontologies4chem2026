"""
Stand-alone SHACL validation script: builds ONE data graph out of the crate plus every
ontology and library file - the way they would also sit together in a named graph in a
GraphDB repository - and validates it against shacl/ContextRequirementShapes.ttl and
shacl/DataQualityShapes.ttl. Counts the results per requirement (matched through
sh:sourceShape; a data-quality shape has no requirement and is counted under its own name)
and writes the same output to reports/shacl_baseline.txt.
Refuses to run when shacl/QuantityKindShapes.ttl no longer matches the ontology (it is
generated by generator/workflow/generate_quantity_kind_shapes.py).

Why the ontologies AND the libraries have to be in the data graph, not just the crate:

- sh:class follows rdfs:subClassOf* only within the graph being validated. Without the
  ontologies, which carry the subClassOf axioms (cpo:GasPhase rdfs:subClassOf cpo:Phase,
  for example), an sh:class check finds no subclass matches even with --inference rdfs,
  because the axioms it would need are not in the graph in the first place.
- Any library may hold fixed entries that a crate entity only points at by IRI
  (hlo:specializationOf) without embedding them. When that library is missing from the data
  graph, the path cannot reach the fixed entry, and phantom warnings appear for exactly
  those requirements that climb through specializationOf up to a fixed entry - for instance
  Molecule_Information_R1 and the three hasInChI/hasSMILES/hasMolecularFormula
  requirements, when chemical_entity_library.jsonld is missing.
- The libraries point into other crates (the usage history of a device: cpo:lastUsedTime of the
  library entry is the end of a procedure in the crate that used it last). In a repository holding
  every crate that node has its type; here only the types of exactly those nodes are added from
  their crates (add_types_from_other_crates) - not their content, and nothing
  else of those crates, so their own findings do not mix in.

Two checks, kept apart: the shapes see the whole data graph, but a crate check
counts only the results whose focus node is a node of the crate file - a library entry, also one the
crate points at, is the business of the library check. That one (--libraries) loads the ontologies,
the libraries and the types from the crates, counts the results at the nodes of the library files,
and writes its own baseline (LIBRARY_BASELINE). Each check also says how many results it left to
the other one ("Not counted"). Run the crate check after building a crate, the library check
after editing the libraries.

Run from the repository root:
    PYTHONPATH=. python generator/workflow/run_shacl.py
    PYTHONPATH=. python generator/workflow/run_shacl.py --inference rdfs
    python generator/workflow/run_shacl.py --crate projects/<crate_identifier>/crate/ro-crate-metadata.json
    python generator/workflow/run_shacl.py --libraries [--inference rdfs]
"""
import argparse
import sys
from pathlib import Path

# Runs from generator/<folder>/ - the generator has to be on the search path.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

import pyshacl
from rdflib import Graph, Namespace, RDF
from rdflib.util import guess_format

import path_definitions

# Namespace of the crate IDs (prefix "crate" in generator/config/project_context.jsonld).
CRATE_IRI = "https://example.org/crate/"
from workflow.generate_quantity_kind_shapes import out_of_date_message
from workflow.generate_function_shapes import out_of_date_message as functions_out_of_date_message

SH = Namespace("http://www.w3.org/ns/shacl#")
HLO = Namespace("http://www.semanticweb.org/lf576/ontologies/2026/7/HigherLevelOntology#")
SCHEMA = Namespace("http://schema.org/")

RDF_EXTENSIONS = (".rdf", ".ttl", ".jsonld", ".owl")

# Baseline of the library check (--libraries), with the documentation. Deliberately not
# under libraries/: a run stops as long as something is uncommitted there, and commits everything under it at
# the end (helpers/git_functions.py).
LIBRARY_BASELINE = path_definitions.BASE_FOLDER / "docs" / "reports" / "library_shacl_baseline.txt"

# Notes printed under a requirement. Deliberately empty: an entry here stands under EVERY future
# hit of this requirement, also under one that reports a real error - so it belongs only where
# the requirement fires for a reason that cannot be fixed.
KNOWN_NOTES = {}

# The same traversal as generator/workflow/summarize_shacl_report.py (there via the message text,
# here directly via the identity of the shape node, as supplied by sh:sourceShape) - covers all
# ways by which a MainShape/ContextPathShape carrying a requirement reaches a deeper
# property/core/member shape.
SHAPE_PATH_QUERY = """
PREFIX sh: <http://www.w3.org/ns/shacl#>
PREFIX rdf: <http://www.w3.org/1999/02/22-rdf-syntax-ns#>
SELECT ?shape WHERE {
    ?main_shape (sh:property|sh:not|sh:qualifiedValueShape|sh:node
                 |sh:or/rdf:rest*/rdf:first
                 |sh:and/rdf:rest*/rdf:first)* ?shape .
}
"""


def find_rdf_files(folder: Path) -> list:
    return sorted(p for p in folder.rglob("*") if p.suffix.lower() in RDF_EXTENSIONS)


def load_into(graph: Graph, path: Path, lines: list):
    """Parse a single file directly into 'graph' (rather than into a separate Graph
    instance that is then unioned in - see below) and print its triple count. Aborts
    immediately on a parse error rather than skipping the file, as required.

    Reads the file content as text and hands it to rdflib directly instead of a path
    string, because otherwise rdflib mistakes a Windows path such as "C:\\..." for a URL
    with the scheme "c" (the same trick is used in shacl/summarize_shacl_report.py).

    Deliberately ONE parse call straight into the shared graph instead of parsing into a
    separate Graph instance and merging with +=: rdflib hands out fresh, unique blank node
    labels on every parse() call, whereas parsing separately and then unioning could
    wrongly merge blank nodes of two files that happen to carry the same label.
    """
    resolved = path.resolve()
    fmt = guess_format(str(resolved))
    if fmt is None:
        print(f"ERROR: '{path}' - no RDF format recognized for the extension '{path.suffix}'.")
        sys.exit(1)

    before = len(graph)
    try:
        text = resolved.read_text(encoding="utf-8")
        graph.parse(data=text, format=fmt, publicID=resolved.as_uri())
    except Exception as error:
        print(f"ERROR while parsing '{path}' (format '{fmt}'): {error}")
        sys.exit(1)

    added = len(graph) - before
    line = f"  {path}: {added} triples"
    print(line)
    lines.append(line)


def build_data_graph(crate_path: Path, lines: list, own_nodes: set = None) -> Graph:
    """Crate, ontologies, libraries and the types from other crates in one graph. With own_nodes,
    the subjects of the crate file are added to it - the nodes a crate check counts."""
    graph = Graph()

    lines.append("Loaded files:")
    print("Loaded files:")
    load_into(graph, crate_path, lines)
    # Right after the crate: everything that is a subject now stands in the crate file.
    if own_nodes is not None:
        own_nodes.update(graph.subjects())

    for folder in (path_definitions.ONTOLOGY_FOLDER, path_definitions.LIBRARY_FOLDER):
        for file_path in find_rdf_files(folder):
            load_into(graph, file_path, lines)
    add_types_from_other_crates(graph, crate_path, lines)

    total_line = f"Data graph in total: {len(graph)} triples"
    print(total_line)
    lines.append(total_line)
    return graph


def build_library_graph(lines: list, own_nodes: set = None) -> Graph:
    """Ontologies, libraries and the types from the crates, without a crate. With own_nodes, the
    subjects the library files bring in are added to it - the nodes the library check counts."""
    graph = Graph()

    lines.append("Loaded files:")
    print("Loaded files:")
    for file_path in find_rdf_files(path_definitions.ONTOLOGY_FOLDER):
        load_into(graph, file_path, lines)
    before = set(graph.subjects())
    for file_path in find_rdf_files(path_definitions.LIBRARY_FOLDER):
        load_into(graph, file_path, lines)
    if own_nodes is not None:
        own_nodes.update(set(graph.subjects()) - before)
    add_types_from_other_crates(graph, None, lines)

    total_line = f"Data graph in total: {len(graph)} triples"
    print(total_line)
    lines.append(total_line)
    return graph


# The nodes of other crates that add_types_from_other_crates gave a type and a name: stand-ins, their data stays in
# their own crate. A shape that reports one (Task_Times_Experiment_Shape misses the times of a procedure the usage
# history of a library points at) says nothing about the crate checked - summarize_results leaves such results out
# of both counts and names them in a line of their own.
OTHER_CRATE_STAND_INS = set()


def add_types_from_other_crates(graph: Graph, crate_path: Path | None, lines: list):
    """rdf:type and schema:name of every node of another crate that the data graph points at
    without knowing its type - read from that crate (open or completed); the name so that
    Name_Shape (rule 1.4) does not report a node whose data stays in its own crate. crate_path:
    the crate in the graph (skipped), None for the library check. The nodes go into
    OTHER_CRATE_STAND_INS."""
    untyped = {o for o in graph.objects() if str(o).startswith(CRATE_IRI) and (o, RDF.type, None) not in graph}
    if not untyped:
        return
    added = 0
    for other in path_definitions.open_crate_paths() + path_definitions.archived_crate_paths():
        if crate_path is not None and other.resolve() == crate_path.resolve():
            continue
        other_graph = Graph()
        # As text, not as a path - see load_into.
        other_graph.parse(data=other.resolve().read_text(encoding="utf-8"), format="json-ld",
                          publicID=other.resolve().as_uri())
        for node in list(untyped):
            for type_ in other_graph.objects(node, RDF.type):
                graph.add((node, RDF.type, type_))
                added += 1
            for name in other_graph.objects(node, SCHEMA.name):
                graph.add((node, SCHEMA.name, name))
    OTHER_CRATE_STAND_INS.update(untyped)
    line = f"  types from other crates: {added} (for {len(untyped)} nodes the libraries or the crate point at)"
    print(line)
    lines.append(line)


def build_shape_to_requirement(shapes_graph: Graph) -> dict:
    mapping = {}
    for main_shape, requirement in shapes_graph.subject_objects(HLO.isShapeOfRequirement):
        requirement_id = shapes_graph.qname(requirement)
        for row in shapes_graph.query(SHAPE_PATH_QUERY, initBindings={"main_shape": main_shape}):
            mapping[row.shape] = requirement_id

    # Shapes without a requirement (DataQualityShapes.ttl) run under their own name instead of
    # as "(unassigned)". Only those with a target of their own - the others are part shapes and
    # are captured above via their main shape already.
    for target in (SH.targetClass, SH.targetSubjectsOf, SH.targetObjectsOf, SH.targetNode):
        for main_shape in set(shapes_graph.subjects(target, None)):
            if (main_shape, HLO.isShapeOfRequirement, None) in shapes_graph:
                continue
            shape_id = shapes_graph.qname(main_shape)
            for row in shapes_graph.query(SHAPE_PATH_QUERY, initBindings={"main_shape": main_shape}):
                mapping.setdefault(row.shape, shape_id)
    return mapping


def summarize_results(results_graph: Graph, shape_to_requirement: dict, lines: list, own_nodes: set = None,
                      elsewhere: str = ""):
    """Count the results per requirement. With own_nodes only those whose focus node is one of them;
    the others are counted in one line "Not counted", with elsewhere naming where they belong."""
    from collections import Counter

    counts = Counter()
    left_out = 0
    at_stand_ins = 0
    # Results that hang at another via sh:detail are its reason (pyshacl stores the inner result
    # at the value node for sh:node) - only the outer one is counted, otherwise a finding would
    # count twice, and the inner one carries the default severity Violation.
    details = set(results_graph.objects(None, SH.detail))
    for result in results_graph.subjects(RDF.type, SH.ValidationResult):
        if result in details:
            continue
        if results_graph.value(result, SH.focusNode) in OTHER_CRATE_STAND_INS:
            at_stand_ins += 1
            continue
        if own_nodes is not None and results_graph.value(result, SH.focusNode) not in own_nodes:
            left_out += 1
            continue
        source_shape = results_graph.value(result, SH.sourceShape)
        severity = results_graph.value(result, SH.resultSeverity)
        severity_label = str(severity).split("#")[-1] if severity is not None else "?"
        requirement_id = shape_to_requirement.get(source_shape, "(unzugeordnet)")
        counts[(requirement_id, severity_label)] += 1

    header = f"\n{'Requirement':55} {'Count':>7}  Severity"
    print(header)
    lines.append(header)
    total = 0
    for (requirement_id, severity_label), n in sorted(counts.items()):
        row = f"{requirement_id:55} {n:>7}  {severity_label}"
        print(row)
        lines.append(row)
        total += n
        note = KNOWN_NOTES.get(requirement_id)
        if note:
            note_line = f"    # {note}"
            print(note_line)
            lines.append(note_line)

    total_line = f"\nTotal: {total}"
    print(total_line)
    lines.append(total_line)
    if own_nodes is not None:
        left_line = f"Not counted: {left_out} at nodes outside{elsewhere}"
        print(left_line)
        lines.append(left_line)
    if at_stand_ins:
        stand_in_line = (f"Left out: {at_stand_ins} at nodes of other crates (only their type and name are loaded here - "
                         "their data is checked in their own crate)")
        print(stand_in_line)
        lines.append(stand_in_line)


def main():
    parser = argparse.ArgumentParser(description="Validates crate + ontologies + libraries against ContextRequirementShapes.ttl and DataQualityShapes.ttl.")
    parser.add_argument("--inference", choices=["none", "rdfs"], default="none", help="Switch RDFS inference on/off (default: off).")
    scope = parser.add_mutually_exclusive_group()
    scope.add_argument("--crate", help="Path to the crate file (default: the only open crate in projects/<crate_identifier>/crate/).")
    scope.add_argument("--libraries", action="store_true", help="Check the libraries instead of a crate (baseline of its own).")
    args = parser.parse_args()

    # The quantity kind shapes are generated from the ontology. If they no longer fit it, every
    # result on rule 4.4 would be wrong without anybody noticing - so do not validate at all.
    # The same for the function shapes (rule 4.9), generated from cpo:offersFunction.
    stale = out_of_date_message() or functions_out_of_date_message()
    if stale:
        print(f"STOPPED: {stale}")
        sys.exit(1)

    own_nodes = set()
    if args.libraries:
        lines = [f"=== SHACL-Baseline (inference={args.inference}, libraries) ==="]
        print(lines[0])
        data_graph = build_library_graph(lines, own_nodes)
        elsewhere = " of the libraries (ontologies, types from crates)"
    else:
        if args.crate is None:
            args.crate = str(path_definitions.default_crate_path())
        lines = [f"=== SHACL-Baseline (inference={args.inference}, crate={args.crate}) ==="]
        print(lines[0])
        data_graph = build_data_graph(Path(args.crate), lines, own_nodes)
        elsewhere = " of the crate (libraries: run_shacl.py --libraries)"

    shapes_graph = Graph()
    shapes_graph.parse(str(path_definitions.CONTEXT_SHAPES), format="turtle")
    shapes_graph.parse(str(path_definitions.DATA_QUALITY_SHAPES), format="turtle")
    shapes_graph.parse(str(path_definitions.QUANTITY_KIND_SHAPES), format="turtle")
    shapes_graph.parse(str(path_definitions.FUNCTION_SHAPES), format="turtle")
    shape_to_requirement = build_shape_to_requirement(shapes_graph)

    _, results_graph, _ = pyshacl.validate(
        data_graph,
        shacl_graph=shapes_graph,
        inference=args.inference,
        advanced=True,
        js=False,
    )

    summarize_results(results_graph, shape_to_requirement, lines, own_nodes, elsewhere)

    # The report belongs to the crate checked: projects/<crate_identifier>/reports/ (also in a copy);
    # that of the libraries in its own place.
    if args.libraries:
        report_path = LIBRARY_BASELINE
    else:
        report_path = Path(args.crate).resolve().parent.parent / "reports" / "shacl_baseline.txt"
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"\nWritten to: {report_path}")


if __name__ == "__main__":
    main()
