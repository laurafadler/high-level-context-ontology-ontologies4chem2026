"""
Write shapes/FunctionShapes.ttl: a task realizes only functions its class offers (rule 4.9),
as plain SHACL Core, one shape per task class, generated from the ontology.

Which functions a task class offers is stated once, in the ontology (cpo:offersFunction on the
class names branches; a branch brings every function under it through cpo:hasBroaderFunction;
a class without a declaration inherits its superclass's - the same reading as
creation/task_functions.py: offered_functions). The questionnaire only offers these, but an
answer file, a setup sheet or an ELN mapping can still name another one; this check catches it.

For every task class with a declaration that narrows the choice:
    every cpo:realizesFunction of an instance (of the class or a subclass) is one of the
    functions the class offers - unless the task has parts (dcterms:hasPart): a section
    takes over the functions of its parts (inherit_group_functions), and those come from
    other classes.
sh:targetClass reaches the instances of subclasses too, so a subclass is checked against its
own list and against every list above it; a declaration only ever narrows the one above.
The class whose list holds every function (cpo:Task) needs no shape.

Run from the repository root after changing cpo:offersFunction or the function list:
    python generator/workflow/generate_function_shapes.py            write the file
    python generator/workflow/generate_function_shapes.py --check    exit 1 if the file is out of date
"""
import argparse
import sys
from pathlib import Path

from rdflib import Graph, Namespace, RDF

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
import path_definitions  # noqa: E402

CPO = Namespace("http://www.semanticweb.org/lf576/ontologies/2026/7/ChemicalProcessOntology#")
OUT = path_definitions.FUNCTION_SHAPES


def local(iri) -> str:
    return str(iri).rsplit("#", 1)[-1].rsplit("/", 1)[-1]


def offered_by_class(ontology: Graph) -> dict:
    """class -> sorted functions it offers (local names), for every class that declares
    cpo:offersFunction itself."""
    functions = set(ontology.subjects(RDF.type, CPO.Function))
    narrower = {}
    for function, broader in ontology.subject_objects(CPO.hasBroaderFunction):
        narrower.setdefault(broader, set()).add(function)
    result = {}
    for cls in set(ontology.subjects(CPO.offersFunction, None)):
        offered, pending = set(), list(ontology.objects(cls, CPO.offersFunction))
        while pending:
            function = pending.pop()
            if function in offered:
                continue
            offered.add(function)
            pending.extend(narrower.get(function, ()))
        assert offered <= functions, (cls, offered - functions)
        result[cls] = sorted(local(f) for f in offered)
    return dict(sorted(result.items(), key=lambda item: local(item[0])))


def shape_for(cls, offered: list) -> str:
    name = local(cls)
    listed = " ".join(f"cpo:{f}" for f in offered)
    return f'''hlo:Function_{name}_Shape
    a sh:NodeShape ;
    sh:targetClass cpo:{name} ;
    sh:or (
        [ sh:path dcterms:hasPart ; sh:minCount 1 ]
        [ sh:path cpo:realizesFunction ; sh:in ( {listed} ) ]
    ) ;
    sh:severity sh:Violation ;
    sh:message "A task of class cpo:{name} (or a subclass) without parts realizes a function its class does not offer (cpo:offersFunction): allowed are {", ".join(offered)}." .

'''


def render(offers: dict, all_functions: int) -> str:
    out = ["""@prefix sh: <http://www.w3.org/ns/shacl#> .
@prefix hlo: <http://www.semanticweb.org/lf576/ontologies/2026/7/HigherLevelOntology#> .
@prefix cpo: <http://www.semanticweb.org/lf576/ontologies/2026/7/ChemicalProcessOntology#> .
@prefix dcterms: <http://purl.org/dc/terms/> .

#################################################################
#
# Functions per task class (rule 4.9) - GENERATED, do not edit by hand
#
#################################################################
#
# Generated by generator/workflow/generate_function_shapes.py from cpo:offersFunction and
# cpo:hasBroaderFunction in the ChemicalProcessOntology. After a change there, run the script
# again; --check reports when this file is out of date. Plain SHACL Core, so that the check
# also runs in GraphDB. A task with parts is excluded: a section inherits the functions of its
# parts, and those come from other classes.

"""]
    for cls, offered in offers.items():
        if len(offered) == all_functions:
            continue
        out.append(shape_for(cls, offered))
    return "".join(out)


def _render_from(ontology: Graph) -> str:
    return render(offered_by_class(ontology), len(set(ontology.subjects(RDF.type, CPO.Function))))


def out_of_date_message(ontology: Graph = None):
    """None if FunctionShapes.ttl is what this script would write from the current ontology,
    otherwise the message to show. Used by --check and generator/workflow/run_shacl.py."""
    if ontology is None:
        ontology = Graph().parse(str(path_definitions.CPO_ONTOLOGY))
    current = OUT.read_text(encoding="utf-8") if OUT.exists() else None
    if current == _render_from(ontology):
        return None
    return (f"{OUT.name} does not match cpo:offersFunction in the ontology (out of date or edited by hand) - "
            f"run generator/workflow/generate_function_shapes.py")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="only compare, exit 1 if the file is out of date")
    args = parser.parse_args()
    ontology = Graph().parse(str(path_definitions.CPO_ONTOLOGY))
    if args.check:
        message = out_of_date_message(ontology)
        if message:
            sys.exit(message)
        print(f"{OUT.name} is up to date.")
        return
    OUT.write_text(_render_from(ontology), encoding="utf-8", newline="\n")
    offers = offered_by_class(ontology)
    print(f"{OUT.name}: {len(offers)} task classes with cpo:offersFunction.")


if __name__ == "__main__":
    main()
